<?php

namespace App\Support;

class Translit
{
    /**
     * Українська → латиниця для ЧПУ-URL (на основі національного стандарту).
     * Латиниця, цифри та розділові знаки проходять без змін -
     * далі рядок все одно прогониться через Str::slug().
     */
    private const MAP = [
        'а' => 'a',  'б' => 'b',  'в' => 'v',  'г' => 'h',  'ґ' => 'g',
        'д' => 'd',  'е' => 'e',  'є' => 'ie', 'ж' => 'zh', 'з' => 'z',
        'и' => 'y',  'і' => 'i',  'ї' => 'i',  'й' => 'i',  'к' => 'k',
        'л' => 'l',  'м' => 'm',  'н' => 'n',  'о' => 'o',  'п' => 'p',
        'р' => 'r',  'с' => 's',  'т' => 't',  'у' => 'u',  'ф' => 'f',
        'х' => 'kh', 'ц' => 'ts', 'ч' => 'ch', 'ш' => 'sh', 'щ' => 'shch',
        'ь' => '',   'ю' => 'iu', 'я' => 'ia',
        
        "'" => '', '’' => '', 'ʼ' => '',
        
        'ё' => 'e', 'ъ' => '', 'ы' => 'y', 'э' => 'e',
    ];

    public static function uk(string $value): string
    {
        $value = mb_strtolower($value, 'UTF-8');

        return strtr($value, self::MAP);
    }
}
